/**
 * الفصل الجاري بالتاريخ، بمواعيد الأستاذ:
 *   سبتمبر ← ديسمبر: الفصل الأول
 *   جانفي ← مارس: الفصل الثاني
 *   أفريل ← منتصف جوان: الفصل الثالث
 *   بعد منتصف جوان وحتى أوت: عطلة، لا فصل جاريًا.
 *
 * الحدّ شهريّ لا يوميّ عن قصد: انتقال الفصل في المدرسة يختلف يومه بين سنة وأخرى،
 * فيُستعمل للتنبيه وحده ولا يمنع التنقيط في أيّ فصل.
 */
export function currentTerm(date: Date): 1 | 2 | 3 | null {
  const month = date.getMonth() + 1; // 1..12
  if (month >= 9) return 1;
  if (month <= 3) return 2;
  if (month <= 5) return 3;
  if (month === 6 && date.getDate() <= 15) return 3;
  return null;
}
